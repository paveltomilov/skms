/**
 * Шаблоны неисправностей для элементов схемы управления и силовой части.
 *
 * Каждый элемент схемы имеет тип (kind) и набор шаблонов неисправностей.
 * Шаблоны определяют возможные типы неисправностей для каждого вида элементов.
 *
 * Структура шаблона:
 * - suffix: суффикс, добавляемый к ID элемента (например, '.1', '.2', '.3')
 * - name: описание неисправности на русском языке
 *
 * При генерации неисправностей через buildMalfunctions() создаются полные ID:
 * baseId + suffix (например, 'c.0.1', 'c.0.2', 'c.0.3')
 */

import type { MalfTpl, ElementKind } from '@/shared/types/scheme';

/**
 * Интерфейс неисправности элемента схемы.
 *
 * @property id - Полный ID неисправности (baseId + suffix, например, 'c.0.1')
 * @property name - Описание неисправности на русском языке
 * @property active - Флаг активности неисправности (true - неисправность активна)
 */
interface Malfunction {
	id: string;
	name: string;
	active: boolean;
}

/**
 * Тип для ID элементов схемы.
 * Принимает только валидные константы из './constants' или './powerCircuit/constants'.
 *
 * @example
 * 'c.0.1' - для цепи управления
 * 'p.0.0.1' - для силовой цепи
 */
type ElementId = string;

