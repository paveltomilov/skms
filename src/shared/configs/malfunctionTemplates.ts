// ======================== Маппинг kind -> шаблон ========================

/**
 * Маппинг типа элемента (kind) на соответствующий шаблон неисправностей.
 * Используется для автоматического выбора шаблона на основе типа элемента.
 * Для проводов используется шаблон MALF_TPL_WIRE_FULL по умолчанию.
 */
const KIND_TO_TEMPLATE_MAP: Record<ElementKind, readonly MalfTpl[]> = {
	wire: MALF_TPL_WIRE_FULL,
	breaker: MALF_TPL_BREAKER,
	limitSwitch: MALF_TPL_LIMIT_SWITCH,
	blockingContact: MALF_TPL_CONTACT_SIGNAL,
	coil: MALF_TPL_COIL,
	lamp: MALF_TPL_LAMP,
	starterContact: MALF_TPL_STARTER_CONTACT,
	motorWinding: MALF_TPL_MOTOR_WINDING,
} as const;

// ======================== Генератор неисправностей ========================

/**
 * Генерирует массив неисправностей на основе ID элемента и его типа (kind).
 * Автоматически выбирает шаблон неисправностей на основе типа элемента.
 *
 * @param baseId - ID элемента схемы. Используйте константы из:
 *   - './controlCircuit/constants' для цепи управления
 *   - './powerCircuit/constants' для силовой цепи
 * @param kind - Тип элемента (kind), на основе которого выбирается шаблон неисправностей
 * @returns Массив неисправностей с полными ID, названиями и состоянием (active: false по умолчанию)
 *
 * @example
 * // Для катушки пускателя
 * buildMalfunctions(COIL_OPEN_ID, 'coil')
 * // => [
 * //   { id: 'c.3.0.4.1.4.1', name: 'Неисправна катушка, пускатель не подтягивается', active: false }
 * // ]
 *
 * @example
 * // Для провода
 * buildMalfunctions(WIRE_POWER_TO_CONTROL_BREAKER_ID, 'wire')
 * // => [
 * //   { id: 'c.0.1', name: 'Обрыв провода', active: false },
 * //   { id: 'c.0.2', name: 'Короткое замыкание', active: false },
 * //   { id: 'c.0.3', name: 'Короткое замыкание на землю', active: false },
 * //   { id: 'c.0.4', name: 'Короткое замыкание с соседним проводом', active: false }
 * // ]
 *
 * @example
 * // Для автомата
 * buildMalfunctions(CONTROL_CIRCUIT_BREAKER_ID, 'breaker')
 * // => [
 * //   { id: 'c.0.1', name: 'Плохой контакт на клемме, нет фазы', active: false },
 * //   { id: 'c.0.2', name: 'Ложно выбивает', active: false },
 * //   { id: 'c.0.3', name: 'Собирается механически, но нет коммутации', active: false }
 * // ]
 */
export function buildMalfunctions(
	baseId: ElementId,
	kind: ElementKind,
): Malfunction[] {
	const templates = KIND_TO_TEMPLATE_MAP[kind];

	if (!templates) {
		throw new Error(`Шаблон неисправностей не найден для kind: ${kind}. `);
	}

	return templates.map(t => ({
		id: `${baseId}${t.suffix}`,
		name: t.name,
		active: false, // По умолчанию все неисправности неактивны
	}));
}
